                           : 'table-success';
  
                tr.innerHTML = `
                    <td>${row.duration}</td>
                    <td>${row.rate} Euro</td>
                `;
                tbody.appendChild(tr);
            });
        })
        .catch(error => console.error('Error fetching data:', error));
  });
  
  
  
